import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = process.cwd();
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'sn-adapter-regression-'));
try {
  const repo = path.join(temp, '.slightnudge/repositories/sample');
  fs.mkdirSync(path.join(repo, 'node_modules/next'), { recursive: true });
  fs.mkdirSync(path.join(temp, 'lib/slightnudge'), { recursive: true });
  fs.copyFileSync(path.join(root, 'lib/slightnudge/next-source-loader.cjs'), path.join(temp, 'lib/slightnudge/next-source-loader.cjs'));
  fs.writeFileSync(path.join(repo, 'package.json'), JSON.stringify({ type: 'module', dependencies: { next: '14.2.35' } }));
  fs.writeFileSync(path.join(repo, 'node_modules/next/package.json'), JSON.stringify({ version: '14.2.35' }));
  fs.writeFileSync(path.join(repo, 'next.config.mjs'), `let calls = 0; export default { webpack(config) { if (++calls !== 1) throw new Error('Original hook called more than once'); config.originalHookRan = true; return config; } };`);
  fs.writeFileSync(path.join(temp, '.slightnudge/repositories.json'), JSON.stringify([{ id: 'sample', localPath: repo }]));
  process.chdir(temp);
  const { installNextSourceAdapter, removeNextSourceAdapter, getNextSourceAdapterStatus } = await import(pathToFileURL(path.join(root, 'lib/slightnudge/next-source-adapter.ts')).href);
  await installNextSourceAdapter('sample');
  const wrapper = (await import(pathToFileURL(path.join(repo, 'next.config.mjs')).href)).default;
  const config = await wrapper('phase-development-server', {});
  const webpack = { module: { rules: [] }, entry: async () => ({ 'main-app': ['existing-entry'] }) };
  const result = await config.webpack(webpack, { dev: true, isServer: false });
  assert.equal(result.originalHookRan, true, 'Existing hook must execute exactly once without recursion');
  assert.equal(result.module.rules.length, 1, 'Development must get exactly one loader rule');
  const entries = await result.entry();
  assert.equal(entries['main-app'].length, 2, 'Existing entry must be preserved with one bridge entry');
  assert.equal(entries['main-app'][1], 'existing-entry');
  assert.deepEqual(await getNextSourceAdapterStatus('sample'), { enabled: true, needsUpdate: false });
  const configPath = path.join(repo, 'next.config.mjs');
  const backupPath = path.join(repo, 'next.config.slightnudge-original.mjs');
  const adapter = path.join(repo, '.slightnudge-source-adapter');
  const original = fs.readFileSync(backupPath, 'utf8'), generated = fs.readFileSync(configPath, 'utf8');
  fs.appendFileSync(configPath, '\n// Local customization');
  await assert.rejects(removeNextSourceAdapter('sample'), /local changes/);
  assert.equal(fs.readFileSync(backupPath, 'utf8'), original);
  assert.ok(fs.readFileSync(configPath, 'utf8').includes('Local customization'));
  fs.writeFileSync(configPath, generated);
  fs.renameSync(backupPath, backupPath + '.held');
  await assert.rejects(removeNextSourceAdapter('sample'), /missing/);
  assert.equal(fs.readFileSync(configPath, 'utf8'), generated, 'Missing backup must not delete the active config');
  fs.renameSync(backupPath + '.held', backupPath);
  const bridgePath = path.join(adapter, 'bridge-client.mjs'), bridge = fs.readFileSync(bridgePath, 'utf8');
  fs.appendFileSync(bridgePath, '\n// Local bridge customization');
  await assert.rejects(removeNextSourceAdapter('sample'), /local changes/);
  assert.equal(fs.readFileSync(configPath, 'utf8'), generated);
  fs.writeFileSync(bridgePath, bridge);
  const statePath = path.join(adapter, 'state.json'), state = JSON.parse(fs.readFileSync(statePath, 'utf8'));
  fs.writeFileSync(statePath, JSON.stringify({ ...state, wrapperName: '../outside.mjs' }));
  await assert.rejects(removeNextSourceAdapter('sample'), /unreadable/);
  fs.writeFileSync(statePath, JSON.stringify({ ...state, protocol: 1 }));
  assert.equal((await getNextSourceAdapterStatus('sample')).needsUpdate, true);
  fs.writeFileSync(statePath, JSON.stringify(state));
  fs.renameSync(adapter, adapter + '.held');
  fs.symlinkSync(adapter + '.held', adapter, 'junction');
  await assert.rejects(removeNextSourceAdapter('sample'), /unreadable/);
  assert.equal(fs.readFileSync(configPath, 'utf8'), generated, 'Replaced adapter folders must not trigger config removal');
  fs.unlinkSync(adapter); fs.renameSync(adapter + '.held', adapter);
  fs.writeFileSync(path.join(adapter, 'personal-notes.txt'), 'Keep my notes');
  await removeNextSourceAdapter('sample');
  assert.equal(fs.readFileSync(configPath, 'utf8'), original);
  assert.equal(fs.readFileSync(path.join(adapter, 'personal-notes.txt'), 'utf8'), 'Keep my notes');
  await assert.rejects(installNextSourceAdapter('sample'), /folder already exists/);
  fs.unlinkSync(path.join(adapter, 'personal-notes.txt')); fs.rmdirSync(adapter);
  fs.writeFileSync(backupPath, 'Existing backup');
  await assert.rejects(installNextSourceAdapter('sample'), /already exists/);
  assert.equal(fs.readFileSync(configPath, 'utf8'), original, 'Backup collision must not delete the original config');
  assert.equal(fs.readFileSync(backupPath, 'utf8'), 'Existing backup');
  fs.unlinkSync(backupPath);
  fs.unlinkSync(path.join(temp, 'lib/slightnudge/next-source-loader.cjs'));
  await assert.rejects(installNextSourceAdapter('sample'), /ENOENT/);
  assert.equal(fs.readFileSync(configPath, 'utf8'), original, 'Failure before config backup must leave the original config intact');
  fs.copyFileSync(path.join(root, 'lib/slightnudge/next-source-loader.cjs'), path.join(temp, 'lib/slightnudge/next-source-loader.cjs'));
  const typed = path.join(temp, '.slightnudge/repositories/typed');
  fs.mkdirSync(path.join(typed, 'node_modules/next'), { recursive: true });
  fs.writeFileSync(path.join(typed, 'node_modules/next/package.json'), '{"version":"16.4.3"}');
  fs.writeFileSync(path.join(typed, 'package.json'), '{"dependencies":{"next":"16.4.3"}}');
  const typedSource = 'import type { NextConfig } from "next"; const config: NextConfig = { webpack(value) { value.originalTypedHook = true; return value; } }; export default config;';
  fs.writeFileSync(path.join(typed, 'next.config.ts'), typedSource);
  fs.writeFileSync(path.join(temp, '.slightnudge/repositories.json'), JSON.stringify([{ id: 'sample', localPath: repo }, { id: 'typed', localPath: typed }]));
  await installNextSourceAdapter('typed');
  assert.equal((await getNextSourceAdapterStatus('typed')).needsUpdate, false);
  const typedStatePath = path.join(typed, '.slightnudge-source-adapter/state.json'), typedState = JSON.parse(fs.readFileSync(typedStatePath, 'utf8'));
  fs.writeFileSync(typedStatePath, JSON.stringify({ ...typedState, configRevision: undefined }));
  assert.equal((await getNextSourceAdapterStatus('typed')).needsUpdate, true, 'Older TypeScript wrappers must offer an adapter update');
  fs.writeFileSync(typedStatePath, JSON.stringify(typedState));
  const loaderScript = `const {transpileConfig}=require(${JSON.stringify(path.join(root, 'node_modules/next/dist/build/next-config-ts/transpile-config.js'))});
    (async()=>{const module=await transpileConfig({nextConfigPath:${JSON.stringify(path.join(typed, 'next.config.ts'))},dir:${JSON.stringify(typed)}});const config=await(module.default||module)('phase-development-server',{});const value=await config.webpack({module:{rules:[]},entry:async()=>({'main-app':[]})},{dev:true,isServer:false});const production=await config.webpack({module:{rules:[]},entry:async()=>({'main-app':[]})},{dev:false,isServer:false});console.log(JSON.stringify({originalTypedHook:value.originalTypedHook,rules:value.module.rules.length,productionRules:production.module.rules.length}));})().catch(error=>{console.error(error);process.exitCode=1});`;
  const loaded = JSON.parse(execFileSync(process.execPath, ['-e', loaderScript], { cwd: typed, encoding: 'utf8', windowsHide: true }));
  assert.deepEqual(loaded, { originalTypedHook: true, rules: 1, productionRules: 0 });
  await removeNextSourceAdapter('typed');
  assert.equal(fs.readFileSync(path.join(typed, 'next.config.ts'), 'utf8'), typedSource);
  console.log('PASS adapter compatibility and integrity: actual Next TypeScript config loader, preserved typed config/hook, existing webpack hook, loader/entry, protocol detection, modified config/bridge, missing backup, invalid state paths, preserved unknown files, install rollback');
} finally {
  process.chdir(root);
  assert.ok(path.resolve(temp).startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(temp).startsWith('sn-adapter-regression-'));
  try { fs.rmSync(temp, { recursive: true, force: true }); }
  catch { console.log(`Manual cleanup required: ${temp}`); }
}
