import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { applyPendingSourceEdit, createPendingSourceEdit, getSourceApplyOutcome, readHistory, undoSourceEdit } from '../lib/slightnudge/edit-history';
import { POST as statusPOST } from '../app/api/slightnudge/apply/status/route';
import { getSessionToken } from '../lib/slightnudge/auth';

const workspace = fs.mkdtempSync(path.join(os.tmpdir(), 'sn-apply-outcome-'));
process.env.SLIGHTNUDGE_TEST = '1';
process.env.SLIGHTNUDGE_WORKSPACE_ROOT = workspace;
process.env.SLIGHTNUDGE_DATA_DIR = path.join(workspace, '.slightnudge');
const file = path.join(workspace, 'page.tsx');
const before = 'export default function Page() { return <h1>Before</h1>; }\n';
const after = before.replace('>Before<', '>After<');
try {
  fs.writeFileSync(file, before);
  assert.equal(getSourceApplyOutcome(randomUUID()), null, 'An unknown operation must not be called a failed save');
  const pending = createPendingSourceEdit({ filePath: file, before, after, oldValue: 'Before', newValue: 'After', summary: 'Change heading', previewType: 'textContent', line: 1 });
  assert.ok(pending.changed);
  assert.equal(getSourceApplyOutcome(pending.id)?.code, 'APPLY_NOT_APPLIED', 'A browser reference can precede any server write intent');
  assert.equal(getSourceApplyOutcome(pending.id, 'wrong-project', 'page.tsx', file)?.code, 'OUTCOME_SCOPE_MISMATCH');
  assert.equal(readHistory().length, 0);
  assert.equal(fs.readFileSync(file, 'utf8'), before, 'Checking an unstarted request never applies the proposal');
  fs.writeFileSync(file, before + '// Outside change\n');
  assert.equal(getSourceApplyOutcome(pending.id)?.code, 'SOURCE_CHANGED');
  assert.equal(readHistory().length, 0);
  fs.writeFileSync(file, before);
  const accepted = await applyPendingSourceEdit(pending.id);
  assert.equal(accepted.success, true);
  // The server accepted the write, but the browser never received this response.
  const recovered = await applyPendingSourceEdit(pending.id);
  assert.equal(recovered.success, true, 'Retrying the accepted preview must recover its receipt');
  assert.equal(recovered.editId, accepted.editId);
  assert.equal(readHistory().length, 1, 'A repeated request must not duplicate history');
  assert.equal(fs.readFileSync(file, 'utf8'), after);
  const restarted = JSON.parse(execFileSync(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', `const {getSourceApplyOutcome}=await import('./lib/slightnudge/edit-history.ts');process.stdout.write(JSON.stringify(getSourceApplyOutcome(${JSON.stringify(pending.id)})));`], { cwd: process.cwd(), env: process.env, encoding: 'utf8' }));
  assert.equal(restarted.editId, accepted.editId, 'A fresh process must recover the persisted receipt');
  const request = (id: string, token = getSessionToken(), origin = 'http://127.0.0.1:3000') => new Request('http://127.0.0.1:3000/api/slightnudge/apply/status', {
    method: 'POST', headers: { host: '127.0.0.1:3000', origin, 'content-type': 'application/json', 'x-slightnudge-token': token }, body: JSON.stringify({ previewId: id }),
  });
  const status = await statusPOST(request(pending.id));
  assert.equal(status.status, 200);
  assert.equal(status.headers.get('cache-control'), 'no-store');
  const payload = await status.json();
  assert.equal(payload.editId, accepted.editId);
  assert.equal('before' in payload || 'after' in payload, false, 'Recovery must not expose source snapshots');
  assert.equal((await statusPOST(request(pending.id, 'wrong-token'))).status, 403);
  assert.equal((await statusPOST(request(pending.id, getSessionToken(), 'https://untrusted.example'))).status, 403);
  const wrongHost = request(pending.id);
  wrongHost.headers.set('host', 'untrusted.example');
  assert.equal((await statusPOST(wrongHost)).status, 403);
  assert.equal((await statusPOST(request('../outside-history'))).status, 400, 'A status identifier cannot traverse paths');
  assert.equal((await (await statusPOST(request(randomUUID()))).json()).code, 'APPLY_UNCERTAIN');
  const external = after + '// Outside edit\n';
  fs.writeFileSync(file, external);
  assert.equal(getSourceApplyOutcome(pending.id)?.success, false, 'A receipt must not approve a changed revision');
  assert.equal((await applyPendingSourceEdit(pending.id)).success, false);
  assert.equal(fs.readFileSync(file, 'utf8'), external, 'A repeated request must preserve outside edits');
  fs.writeFileSync(file, after);
  assert.equal(undoSourceEdit(file).success, true);
  assert.equal((await applyPendingSourceEdit(pending.id)).success, false, 'A receipt must never reapply an undone operation');
  assert.equal(fs.readFileSync(file, 'utf8'), before);
  const groupId = randomUUID();
  const proposal = (original: string, updated: string, context = {}) => {
    const result = createPendingSourceEdit({ filePath: file, before: original, after: updated, oldValue: 'Before', newValue: 'After', summary: 'Change heading', previewType: 'textContent', ...context });
    assert.ok(result.changed); return result.id;
  };
  const firstId = proposal(before, after);
  await applyPendingSourceEdit(firstId, groupId);
  const third = after.replace('After', 'Third');
  const secondId = proposal(after, third);
  await applyPendingSourceEdit(secondId, groupId);
  assert.equal(readHistory().at(-1)?.previewIds?.length, 2, 'Grouped history must retain both proposal identities');
  assert.equal(getSourceApplyOutcome(firstId)?.success, false, 'An earlier grouped proposal cannot confirm a later revision');
  assert.equal(getSourceApplyOutcome(secondId)?.success, true);
  assert.equal(undoSourceEdit(file).success, true);
  assert.equal(fs.readFileSync(file, 'utf8'), before);
  assert.equal((await applyPendingSourceEdit(firstId)).success, false);
  assert.equal((await applyPendingSourceEdit(secondId)).success, false);
  const importedId = proposal(before, after, { repositoryId: 'project-a', sourcePath: 'page.tsx' });
  assert.equal((await applyPendingSourceEdit(importedId, undefined, 'project-a', 'page.tsx', file)).success, true);
  assert.equal(getSourceApplyOutcome(importedId)?.success, false, 'Workspace recovery cannot read an imported-project receipt');
  assert.equal((await (await statusPOST(request(importedId))).json()).code, 'OUTCOME_SCOPE_MISMATCH');
  assert.equal(getSourceApplyOutcome(importedId, 'project-b', 'page.tsx', file)?.success, false);
  assert.equal(getSourceApplyOutcome(importedId, 'project-a', 'other.tsx', file)?.success, false);
  assert.equal(getSourceApplyOutcome(importedId, 'project-a', 'page.tsx', path.join(workspace, 'other.tsx'))?.success, false);
  assert.equal(getSourceApplyOutcome(importedId, 'project-a', 'page.tsx', file)?.success, true);
  assert.equal(fs.readFileSync(file, 'utf8'), after);
  fs.symlinkSync(path.join(process.cwd(), 'node_modules'), path.join(workspace, 'node_modules'), 'junction');
  fs.writeFileSync(path.join(workspace, 'package.json'), JSON.stringify({ dependencies: { tailwindcss: JSON.parse(fs.readFileSync(path.join(process.cwd(), 'node_modules/tailwindcss/package.json'), 'utf8')).version } }));
  fs.mkdirSync(path.join(workspace, 'app'));
  fs.writeFileSync(path.join(workspace, 'app/globals.css'), '@import "tailwindcss";\n');
  const classBefore = 'export default function Page() { return <h1 className="font-normal">Before</h1>; }\n';
  const classAfter = classBefore.replace('font-normal', 'font-bold');
  fs.writeFileSync(file, classBefore);
  const concurrent = createPendingSourceEdit({ filePath: file, before: classBefore, after: classAfter, oldValue: 'font-normal', newValue: 'font-bold', summary: 'Bold heading', previewType: 'className' });
  assert.ok(concurrent.changed);
  const historyCount = readHistory().length;
  const simultaneous = await Promise.all([applyPendingSourceEdit(concurrent.id), applyPendingSourceEdit(concurrent.id)]);
  assert.ok(simultaneous.every(result => result.success), 'Concurrent requests awaiting class compilation must recover one accepted operation');
  assert.equal(simultaneous[0].editId, simultaneous[1].editId);
  assert.equal(readHistory().length, historyCount + 1);
  assert.equal(undoSourceEdit(file).success, true);
  assert.equal(fs.readFileSync(file, 'utf8'), classBefore);
  console.log('PASS: Apply outcome recovery (duplicate/concurrent requests, process restart, status auth/origin, no snapshots, outside edits, Undo, grouped receipts, project/file scope)');
} finally {
  const resolved = path.resolve(workspace);
  assert.ok(resolved.startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(resolved).startsWith('sn-apply-outcome-'));
  if (fs.existsSync(path.join(resolved, 'node_modules'))) fs.unlinkSync(path.join(resolved, 'node_modules'));
  fs.rmSync(resolved, { recursive: true, force: true });
}
