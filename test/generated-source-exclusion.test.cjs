const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { Scanner } = require('@tailwindcss/oxide');
const { ts } = require('ts-morph');
const root = fs.mkdtempSync(path.resolve('scratch/generated-scan-'));
for (const dir of ['.git', 'app', 'scratch/generated']) fs.mkdirSync(path.join(root, dir), { recursive: true });
fs.copyFileSync('.gitignore', path.join(root, '.gitignore'));
fs.writeFileSync(path.join(root, 'app/page.tsx'), 'export const page = <div className="p-4"/>;');
fs.writeFileSync(path.join(root, 'scratch/generated/page.tsx'), 'export const generated = <div className="p-[98765px]"/>;');
const scanner = new Scanner({ sources: [{ base: root, pattern: '**/*', negated: false }] });
const candidates = scanner.scan();
const scratchFiles = scanner.files.filter(file => /[\\/]scratch[\\/]generated[\\/]/.test(file));
const config = JSON.parse(fs.readFileSync('tsconfig.json', 'utf8'));
const project = ts.parseJsonConfigFileContent(config, ts.sys, root);
const generatedTypes = project.fileNames.filter(file => /[\\/]scratch[\\/]generated[\\/]/.test(file));
console.log(JSON.stringify({ tailwindGeneratedFiles: scratchFiles.length, typescriptGeneratedFiles: generatedTypes.length }));
assert.equal(scratchFiles.length, 0, 'Tailwind must exclude generated scratch sources');
assert.equal(generatedTypes.length, 0, 'TypeScript must exclude generated scratch sources');
assert.ok(candidates.includes('p-4'), 'Real app utilities remain scanned');
assert.ok(!candidates.includes('p-[98765px]'), 'Generated utilities do not enter the app CSS');
assert.ok(project.fileNames.some(file => file.endsWith('app/page.tsx')), 'Real app TSX remains included');
console.log('PASS generated artifacts excluded; application sources retained');
